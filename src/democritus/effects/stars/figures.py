"""The figures of the constellations: the lines that are drawn between their stars on a star map.

The rows are the lines of 34 constellations from d3-celestial's constellations.lines.json (Olaf Frohn, BSD
3-clause licence, github.com/ofrohn/d3-celestial): every constellation that file ranks most prominent, and
every one of its second rank whose figure is at most 7 lines, which brings in the Southern Cross, Lyra
and the Little Bear at little cost. Every line costs the sky one star: the game draws a fixed number of
quads for its stars, and a line is one of them (see the stars effect). A row holds the right ascension
and the declination of the two ends of one line, and the constellation's abbreviation as a comment.

The rows were written by a script from that file and are not to be edited by hand.
"""

from dataclasses import dataclass

import deal

from democritus.effects.stars.catalogue import Degrees, Hours


@dataclass(frozen=True)
class SkyPlace:
    """A place in the real sky."""

    right_ascension: Hours
    declination: Degrees


@dataclass(frozen=True)
class FigureLine:
    """One line of the figure of a constellation, between two places in the real sky."""

    start: SkyPlace
    end: SkyPlace


def _line(start_hours: float, start_degrees: float, end_hours: float, end_degrees: float) -> FigureLine:
    return FigureLine(
        SkyPlace(Hours(start_hours), Degrees(start_degrees)), SkyPlace(Hours(end_hours), Degrees(end_degrees))
    )


