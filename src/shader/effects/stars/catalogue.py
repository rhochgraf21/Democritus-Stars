"""The brightest stars of the real sky: where each is, how bright and what colour.

The rows are the 780 brightest stars of the Yale Bright Star Catalogue, 5th revised edition (Hoffleit and
Warren 1991, public domain, bsc5.dat from tdc-www.harvard.edu/catalogs), brightest first. 780 is how many
stars the game draws (see the stars effect). A row holds the star's right ascension and declination for
the year 2000, its visual magnitude and its B-V colour index, as the catalogue gives them, and its
catalogue name as a comment. The catalogue lists the fainter star of three close pairs without a colour
index (Gam Vir, Gam2 Leo, Zet Ori); they are left out, since the eye sees each pair as its brighter star.

The rows were written by a script from the catalogue file and are not to be edited by hand.
"""

from dataclasses import dataclass
from typing import NewType

import deal

# A right ascension: the angle around the sky's axis, in hours from 0 to 24.
Hours = NewType("Hours", float)

# A declination: the angle from the sky's equator, in degrees, 90 at the north pole and -90 at the south.
Degrees = NewType("Degrees", float)

# A visual magnitude: how bright a star looks. Lower is brighter, and 5 lower is a hundred times the light.
Magnitude = NewType("Magnitude", float)

# A B-V colour index: about -0.3 for the bluest stars, 0 for white, 2 for the reddest.
ColourIndex = NewType("ColourIndex", float)


@dataclass(frozen=True)
class CatalogueStar:
    """One star of the real sky."""

    right_ascension: Hours
    declination: Degrees
    magnitude: Magnitude
    colour_index: ColourIndex


def _star(right_ascension: float, declination: float, magnitude: float, colour_index: float) -> CatalogueStar:
    return CatalogueStar(Hours(right_ascension), Degrees(declination), Magnitude(magnitude), ColourIndex(colour_index))


